export const MISC_APP_LABEL = "Другие";

export function isMiscApp(app: string | null | undefined, bundleId?: string | null): boolean {
  if (bundleId && MISC_BUNDLES.has(bundleId)) return true;
  if (!app) return false;
  const n = app.trim().toLowerCase();
  if (MISC_NAMES.has(n)) return true;
  // fuzzy: screenshot / settings keywords
  if (/(screenshot|screencapture|cleanshot|shottr|snagit)/i.test(app)) return true;
  if (/^(system settings|system preferences|настройки)/i.test(app)) return true;
  return false;
}

export function normalizeApp(app: string, bundleId?: string | null): string {
  return isMiscApp(app, bundleId) ? MISC_APP_LABEL : app;
}
